#!/usr/bin/env bash
# Writes supabase/hosted-setup.sql: every migration in order, in one file, for pasting into the
# Supabase SQL Editor of an empty hosted project. Also records each version, so the Supabase CLI
# later sees them as applied. Regenerate after adding a migration: npm run db:bundle
set -euo pipefail
cd "$(dirname "$0")/.."
out=supabase/hosted-setup.sql
{
  echo "-- Lorry Book: the whole database in one go. Generated by npm run db:bundle; do not edit."
  echo "-- Supabase → SQL Editor → New query → paste all of this → Run. Once, on an empty project."
  echo "create schema if not exists supabase_migrations;"
  echo "create table if not exists supabase_migrations.schema_migrations (version text primary key, statements text[], name text);"
  for f in supabase/migrations/*.sql; do
    b=$(basename "$f" .sql); v=${b%%_*}; n=${b#*_}
    printf '\n-- ===== %s\n' "$b"; cat "$f"; echo
    echo "insert into supabase_migrations.schema_migrations (version, name) values ('$v', '$n') on conflict do nothing;"
  done
} > "$out"
echo "wrote $out"
